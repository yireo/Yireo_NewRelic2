declare(strict_types=1);

namespace Yireo\NewRelic2\Setup\Patch\Data;

use Magento\Framework\Encryption\EncryptorInterface;
use Magento\Framework\Setup\ModuleDataSetupInterface;
use Magento\Framework\Setup\Patch\DataPatchInterface;

class EncryptLicenseKey implements DataPatchInterface
{
    public const CONFIG_PATH = 'newrelic2/settings/license';

    public function __construct(
        private readonly ModuleDataSetupInterface $moduleDataSetup,
        private readonly EncryptorInterface $encryptor
    ) {
    }

    public function apply(): self
    {
        $connection = $this->moduleDataSetup->getConnection();
        $table = $this->moduleDataSetup->getTable('core_config_data');

        $select = $connection->select()
            ->from($table, ['config_id', 'value'])
            ->where('path = ?', self::CONFIG_PATH);

        foreach ($connection->fetchPairs($select) as $configId => $value) {
            $value = (string)$value;
            if ($value === '' || preg_match('/^\d+:\d+:/', $value)) {
                continue;
            }

            $connection->update(
                $table,
                ['value' => $this->encryptor->encrypt($value)],
                ['config_id = ?' => (int)$configId]
            );
        }

        return $this;
    }

    public static function getDependencies(): array
    {
        return [];
    }

    public function getAliases(): array
    {
        return [];
    }
}
